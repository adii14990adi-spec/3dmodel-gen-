#include "exporters/fbx/fbx_exporter.hpp"

#include <filesystem>
#include <fstream>
#include <sstream>

namespace forge3d::exporters {

FbxExportResult export_fbx(const Mesh& mesh,
                           const std::vector<PBRMaterial>& materials,
                           const std::string& output_path) {
    FbxExportResult result;

    if (mesh.vertex_count() == 0 || mesh.face_count() == 0) {
        result.error = "Mesh has no vertices or faces.";
        return result;
    }

    std::filesystem::path out_p(output_path);
    if (out_p.has_parent_path()) {
        std::filesystem::create_directories(out_p.parent_path());
    }

    std::ofstream out(output_path);
    if (!out) {
        result.error = "Failed to open FBX output file: " + output_path;
        return result;
    }

    std::vector<PBRMaterial> export_mats = materials;
    if (export_mats.empty()) {
        export_mats.push_back(PBRMaterial{});
    }

    const auto& verts = mesh.vertices();
    const auto& faces = mesh.faces();

    const uint64_t model_id = 100001;
    const uint64_t geom_id = 100002;
    const uint64_t base_mat_id = 200000;

    out << "; FBX 7.4.0 project file\n";
    out << "; Generated by Forge3D Independent C++ Engine (Unity 6 Compatible)\n";
    out << "FBXHeaderExtension:  {\n"
        << "\tFBXHeaderVersion: 1003\n"
        << "\tFBXVersion: 7400\n"
        << "\tCreator: \"Forge3D C++ Engine\"\n"
        << "}\n\n";

    out << "GlobalSettings:  {\n"
        << "\tVersion: 1000\n"
        << "\tProperties70:  {\n"
        << "\t\tP: \"UpAxis\", \"int\", \"Integer\", \"\",1\n"
        << "\t\tP: \"UpAxisSign\", \"int\", \"Integer\", \"\",1\n"
        << "\t\tP: \"FrontAxis\", \"int\", \"Integer\", \"\",2\n"
        << "\t\tP: \"FrontAxisSign\", \"int\", \"Integer\", \"\",1\n"
        << "\t\tP: \"CoordAxis\", \"int\", \"Integer\", \"\",0\n"
        << "\t\tP: \"CoordAxisSign\", \"int\", \"Integer\", \"\",1\n"
        << "\t\tP: \"UnitScaleFactor\", \"double\", \"Number\", \"\",100\n"
        << "\t}\n"
        << "}\n\n";

    out << "Objects:  {\n";

    // Geometry
    out << "\tGeometry: " << geom_id << ", \"Geometry::" << mesh.name() << "\", \"Mesh\" {\n";
    out << "\t\tVertices: *" << (verts.size() * 3) << " {\n\t\t\ta: ";
    for (size_t i = 0; i < verts.size(); ++i) {
        if (i > 0) out << ",";
        out << verts[i].position.x << "," << verts[i].position.y << "," << verts[i].position.z;
    }
    out << "\n\t\t}\n";

    // PolygonVertexIndex
    std::vector<int32_t> poly_indices;
    poly_indices.reserve(faces.size() * 4);
    for (const auto& f : faces) {
        if (f.indices.size() < 3) continue;
        for (size_t i = 0; i + 1 < f.indices.size(); ++i) {
            poly_indices.push_back(static_cast<int32_t>(f.indices[i]));
        }
        poly_indices.push_back(-static_cast<int32_t>(f.indices.back()) - 1);
    }

    out << "\t\tPolygonVertexIndex: *" << poly_indices.size() << " {\n\t\t\ta: ";
    for (size_t i = 0; i < poly_indices.size(); ++i) {
        if (i > 0) out << ",";
        out << poly_indices[i];
    }
    out << "\n\t\t}\n";

    // Normals (ByVertice)
    out << "\t\tLayerElementNormal: 0 {\n"
        << "\t\t\tVersion: 101\n"
        << "\t\t\tName: \"\"\n"
        << "\t\t\tMappingInformationType: \"ByVertice\"\n"
        << "\t\t\tReferenceInformationType: \"Direct\"\n"
        << "\t\t\tNormals: *" << (verts.size() * 3) << " {\n\t\t\t\ta: ";
    for (size_t i = 0; i < verts.size(); ++i) {
        if (i > 0) out << ",";
        out << verts[i].normal.x << "," << verts[i].normal.y << "," << verts[i].normal.z;
    }
    out << "\n\t\t\t}\n\t\t}\n";

    // UVs (ByVertice)
    out << "\t\tLayerElementUV: 0 {\n"
        << "\t\t\tVersion: 101\n"
        << "\t\t\tName: \"UVMap\"\n"
        << "\t\t\tMappingInformationType: \"ByVertice\"\n"
        << "\t\t\tReferenceInformationType: \"Direct\"\n"
        << "\t\t\tUV: *" << (verts.size() * 2) << " {\n\t\t\t\ta: ";
    for (size_t i = 0; i < verts.size(); ++i) {
        if (i > 0) out << ",";
        out << verts[i].uv.x << "," << verts[i].uv.y;
    }
    out << "\n\t\t\t}\n\t\t}\n";

    // Materials (ByPolygon)
    out << "\t\tLayerElementMaterial: 0 {\n"
        << "\t\t\tVersion: 101\n"
        << "\t\t\tName: \"\"\n"
        << "\t\t\tMappingInformationType: \"ByPolygon\"\n"
        << "\t\t\tReferenceInformationType: \"IndexToDirect\"\n"
        << "\t\t\tMaterials: *" << faces.size() << " {\n\t\t\t\ta: ";
    for (size_t i = 0; i < faces.size(); ++i) {
        if (i > 0) out << ",";
        uint32_t mid = faces[i].material_id < export_mats.size() ? faces[i].material_id : 0;
        out << mid;
    }
    out << "\n\t\t\t}\n\t\t}\n";

    out << "\t\tLayer: 0 {\n"
        << "\t\t\tVersion: 100\n"
        << "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementNormal\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n"
        << "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementUV\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n"
        << "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementMaterial\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n"
        << "\t\t}\n";
    out << "\t}\n";

    // Model
    out << "\tModel: " << model_id << ", \"Model::" << mesh.name() << "\", \"Mesh\" {\n"
        << "\t\tVersion: 232\n"
        << "\t\tProperties70:  {\n"
        << "\t\t\tP: \"Lcl Translation\", \"Lcl Translation\", \"\", \"A\",0,0,0\n"
        << "\t\t\tP: \"Lcl Rotation\", \"Lcl Rotation\", \"\", \"A\",0,0,0\n"
        << "\t\t\tP: \"Lcl Scaling\", \"Lcl Scaling\", \"\", \"A\",1,1,1\n"
        << "\t\t}\n"
        << "\t}\n";

    // Materials
    for (size_t i = 0; i < export_mats.size(); ++i) {
        const auto& m = export_mats[i];
        out << "\tMaterial: " << (base_mat_id + i) << ", \"Material::" << m.name << "\", \"\" {\n"
            << "\t\tVersion: 102\n"
            << "\t\tShadingModel: \"phong\"\n"
            << "\t\tProperties70:  {\n"
            << "\t\t\tP: \"DiffuseColor\", \"Color\", \"\", \"A\","
            << m.base_color.x << "," << m.base_color.y << "," << m.base_color.z << "\n"
            << "\t\t\tP: \"ReflectionFactor\", \"Number\", \"\", \"A\"," << m.metallic << "\n"
            << "\t\t\tP: \"Shininess\", \"Number\", \"\", \"A\"," << ((1.0f - m.roughness) * 100.0f) << "\n"
            << "\t\t}\n"
            << "\t}\n";
    }
    out << "}\n\n";

    // Connections
    out << "Connections:  {\n";
    out << "\tC: \"OO\"," << model_id << ",0\n";
    out << "\tC: \"OO\"," << geom_id << "," << model_id << "\n";
    for (size_t i = 0; i < export_mats.size(); ++i) {
        out << "\tC: \"OO\"," << (base_mat_id + i) << "," << model_id << "\n";
    }
    out << "}\n";

    out.close();

    result.success = true;
    result.file_size_bytes = static_cast<size_t>(std::filesystem::file_size(output_path));
    result.vertex_count = verts.size();
    result.polygon_count = faces.size();
    result.material_count = export_mats.size();
    return result;
}

bool validate_fbx_file(const std::string& path, std::string* error_out) {
    std::ifstream in(path);
    if (!in) {
        if (error_out) *error_out = "Cannot open FBX file: " + path;
        return false;
    }
    std::string content((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    if (content.find("FBXHeaderExtension:") == std::string::npos ||
        content.find("Objects:") == std::string::npos ||
        content.find("Connections:") == std::string::npos) {
        if (error_out) *error_out = "Missing required FBX sections.";
        return false;
    }
    return true;
}

} // namespace forge3d::exporters
